#!/usr/bin/env python3
"""Mutation fixtures for page-blocks.sh selftest: a.md deletes the first table, b.md changes one
caption, c.md changes one heading. Usage: page-blocks-mutate.py <baseline.md> <out-dir>"""
import sys
base, tmp = sys.argv[1:3]
lines = open(base, encoding="utf-8").read().split("\n")
i = next(i for i, l in enumerate(lines) if l.startswith("|")); j = i
while j < len(lines) and lines[j].startswith("|"): j += 1
open(tmp + "/a.md", "w", encoding="utf-8").write("\n".join(lines[:i] + lines[j:]))
k = next(i for i, l in enumerate(lines) if l.startswith("Generated by")); m = lines[:]; m[k] = m[k].replace("Generated by", "Generated  by")
open(tmp + "/b.md", "w", encoding="utf-8").write("\n".join(m))
h = next(i for i, l in enumerate(lines) if l.startswith("## ")); m = lines[:]; m[h] = m[h] + " (edited)"
open(tmp + "/c.md", "w", encoding="utf-8").write("\n".join(m))
