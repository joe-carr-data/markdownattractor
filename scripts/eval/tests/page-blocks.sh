#!/usr/bin/env bash
# The generated blocks of docs/benchmarks.md survive every restructure byte for byte (M9 plan,
# D2): every markdown table and every "What travels with the table" body that was on the page
# when the baseline was captured must still be present, unchanged, on the page or in the
# archive it moved to. Numbers on the page are never retyped, so a block that differs is a
# retyped number until proven otherwise. Run by `make check` (target page-blocks).
#
# Usage:
#   scripts/eval/tests/page-blocks.sh check [pages...]       # default pages: docs/benchmarks.md docs/archive/benchmarks-development-2026-09.md
#   scripts/eval/tests/page-blocks.sh capture <page> > scripts/eval/tests/page-blocks.sha256
#   scripts/eval/tests/page-blocks.sh blocks <page>          # the blocks, one sha256 and first line per block (debugging)
# A block is (a) a maximal run of lines starting with `|`, (b) the lines between a
# `### What travels with the table` heading and the next heading, (c) a heading line (`#`…),
# or (d) a caption paragraph: a paragraph that starts with "Generated by", "Rendered by",
# "Reproduction:" or "Regeneration" (what the renderers print beside their tables). Blank
# lines inside (b) are kept; trailing blank lines are not part of a block. The baseline is a
# multiset: a block that appears twice must still appear twice. Headings that the restructure
# renames on purpose are listed in page-blocks.renamed (old heading → new heading, tab-separated)
# and checked by their new text (comment lines in that file start with `;`).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"; repo="$(cd "$here/../../.." && pwd)"
baseline="$here/page-blocks.sha256"
cmd="${1:-check}"; shift || true

blocks() { # page -> "sha256  first-line" per block
  PAGE_BLOCKS_DIR="$here" python3 - "$1" <<'PY'
import hashlib, os, re, sys
lines = open(sys.argv[1], encoding="utf-8").read().split("\n")
renamed = {}
rn = os.path.join(os.path.dirname(os.path.realpath(sys.argv[0])) if False else os.environ.get("PAGE_BLOCKS_DIR", "."), "page-blocks.renamed")
if os.path.isfile(rn):
    for line in open(rn, encoding="utf-8"):
        if "\t" in line and not line.startswith(";"):
            new, old = line.rstrip("\n").split("\t")[1], line.rstrip("\n").split("\t")[0]
            renamed[new] = old
out = []
def emit(b):
    while b and b[-1].strip() == "": b.pop()
    if b: out.append(b)
i = 0
while i < len(lines):
    l = lines[i]
    if l.startswith("|"):
        b = []
        while i < len(lines) and lines[i].startswith("|"): b.append(lines[i]); i += 1
        emit(b); continue
    if re.match(r"^#{2,6} What travels with the table", l):
        emit([renamed.get(l, l)])
        i += 1; b = []
        while i < len(lines) and not lines[i].startswith("#"): b.append(lines[i]); i += 1
        emit(b); continue
    if l.startswith("#"):
        emit([renamed.get(l, l)]); i += 1; continue
    if l.startswith(("Generated by", "Rendered by", "Reproduction:", "Regeneration")):
        b = []
        while i < len(lines) and lines[i].strip() != "": b.append(lines[i]); i += 1
        emit(b); continue
    i += 1
for b in out:
    text = "\n".join(b) + "\n"
    print(hashlib.sha256(text.encode("utf-8")).hexdigest(), " ", b[0][:100].replace("\n", " "))
PY
}

case "$cmd" in
  blocks) blocks "${1:?page}" ;;
  capture) blocks "${1:?page}" | cut -c1-64 | sort ;;
  check)
    [ -f "$baseline" ] || { echo "no baseline $baseline (capture it first)" >&2; exit 1; }
    pages=("$@"); [ "${#pages[@]}" -gt 0 ] || pages=("$repo/docs/benchmarks.md" "$repo/docs/archive/benchmarks-development-2026-09.md")
    tmp="$(mktemp -d -t mda-page-blocks.XXXXXX)"; trap 'rm -rf "$tmp"' EXIT
    : > "$tmp/now"
    for p in "${pages[@]}"; do [ -f "$p" ] || continue; blocks "$p" >> "$tmp/now"; done
    cut -c1-64 "$tmp/now" | sort > "$tmp/now.sha"
    sort "$baseline" > "$tmp/base.sha"
    # every baseline hash must be present at least as many times as in the baseline
    missing="$(comm -23 "$tmp/base.sha" "$tmp/now.sha")"
    if [ -n "$missing" ]; then
      echo "page-blocks: $(printf '%s\n' "$missing" | grep -c .) generated block(s) of the baseline are missing or changed:" >&2
      printf '%s\n' "$missing" | cut -c1-12 >&2
      exit 1
    fi
    echo "page-blocks: all $(grep -c . "$baseline") baseline blocks present and unchanged across ${#pages[@]} page(s) ($(grep -c . "$tmp/now.sha") blocks now)" ;;
  readme)
    # the README's numbers row is exactly the renderer's output (never retyped): the block between
    # the benchmark-row markers equals `scripts/eval/t6.sh readme-row` on the committed artifacts
    want="$("$repo/scripts/eval/t6.sh" readme-row)"
    have="$(sed -n '/<!-- benchmark-row:start -->/,/<!-- benchmark-row:end -->/p' "$repo/README.md" | sed '1d;$d')"
    [ -n "$have" ] || { echo "readme: no benchmark-row markers in README.md" >&2; exit 1; }
    if [ "$want" = "$have" ]; then echo "readme: the numbers row equals the renderer's output ($(printf '%s\n' "$have" | grep -c '^| ' ) lines)"; else echo "readme: the numbers row differs from scripts/eval/t6.sh readme-row:" >&2; diff <(printf '%s\n' "$want") <(printf '%s\n' "$have") >&2 || true; exit 1; fi ;;
  *) echo "usage: $0 check|capture <page>|blocks <page>|readme" >&2; exit 2 ;;
esac
