#!/usr/bin/env bash
# Render the DocsQA axis-A table (one row per project and configuration) from the raw
# result files, so the numbers on docs/benchmarks.md are never retyped.
#
# Usage: scripts/eval/table.sh [results-dir=evals/results/docsqa] [split=dev]
# Reads <dir>/<project>/{coverage,results}.json for the four projects and prints Markdown.
set -euo pipefail
dir="${1:-$(cd "$(dirname "$0")/../.." && pwd)/evals/results/docsqa}"
split="${2:-dev}"
echo "| Project | dev scored | run | success@5 | MRR@5 | nDCG@10 | mean ms | truncated |"
echo "|---|---|---|---|---|---|---|---|"
for p in github-docs prisma supabase tailwind-css; do
  f="$dir/$p/results.json"; [ -f "$f" ] || continue
  jq -r --arg p "$p" --arg split "$split" '
    select(.split == $split) | .runs[] |
    "| \($p) | \(.metrics.questions) | \(.run) | \(.metrics.success_at_5 | . * 1000 | round / 1000 | tostring) | \(.metrics.mrr_at_5 | . * 1000 | round / 1000 | tostring) | \(.metrics.ndcg_at_10 | . * 1000 | round / 1000 | tostring) | \(if .metrics.mean_ms == null then "n/a" else (.metrics.mean_ms | round | tostring) end) | \([.results[] | select(.truncated)] | length) |"' "$f"
  # External arms scored through --arm-output (one file per arm under <project>/arms/).
  for a in "$dir/$p"/arms/*.results.json; do
    [ -f "$a" ] || continue
    jq -r --arg p "$p" --arg split "$split" '
      select(.split == $split) | .runs[] |
      "| \($p) | \(.metrics.questions) | \(.run) | \(.metrics.success_at_5 | . * 1000 | round / 1000 | tostring) | \(.metrics.mrr_at_5 | . * 1000 | round / 1000 | tostring) | \(.metrics.ndcg_at_10 | . * 1000 | round / 1000 | tostring) | n/a | \([.results[] | select(.truncated)] | length)\(if (.missing | length) > 0 then " (\(.missing | length) missing)" else "" end) |"' "$a"
  done
done
echo
echo "Generated by \`scripts/eval/table.sh\` from \`evals/results/docsqa/<project>/results.json\` and \`<project>/arms/*.results.json\` (split: $split; mda $(jq -r .mda_version "$dir/tailwind-css/results.json" 2>/dev/null || echo '?'); mean ms is the adapter in-process, release build, and includes the deeper fetches the page rule needs; external arms have no latency column here, their MCP latency is measured by \`scripts/eval/mcp-time.sh\`)."
